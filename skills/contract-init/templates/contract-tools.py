def check_refs(ctx, text, here, label, ids, fms, errors):
    """Links, paths in backticks, contract#clause references and file:line references."""
    def err(msg):
        errors.append(f"{label}: {msg}")

    t = prose(text)
    no_inline = re.sub(r"`[^`\n]*`", "", t)
    for m in re.finditer(r"\[[^\]]*\]\(([^)\s]+)\)", no_inline):
        target = m.group(1)
        if re.match(r"^(https?:|mailto:)", target):
            continue
        p, _, frag = target.partition("#")
        dest = (here.parent / p) if p else here
        if not dest.exists():
            err(f"link to a file that does not exist: {target}")
        elif frag and dest.is_file() and slug(frag) not in anchors(dest):
            err(f"link to a heading that does not exist: {target}")
    for m in re.finditer(r"`([^`\n]+)`", t):
        tok = m.group(1).strip()
        r = re.match(r"^([a-z0-9_]+)#([a-z0-9_]+)$", tok)
        if r:
            if r.group(1) not in ids or r.group(2) not in (fms.get(r.group(1), {}).get("_clauses") or []):
                err(f"reference to a clause that does not exist: {tok}")
            continue
        fl = re.match(r"^(.+?):(\d+)$", tok)
        path, line = (fl.group(1), int(fl.group(2))) if fl else (tok, None)
        if "/" not in path or re.search(r"[\s*<>{}()=|$]", path) or path.startswith(("http", "-")):
            continue
        found = next((c for c in (ctx.root / path, ctx.tests / path, ctx.ws / path, here.parent / path) if c.exists()), None)
        if found is None:
            err(f"path that does not exist: {path}")
        elif line is not None and found.is_file():
            try:
                n = len(found.read_text(encoding="utf-8", errors="replace").splitlines())
            except OSError:
                n = 0
            if line > n:
                err(f"{path} has {n} lines, there is no line {line}")
    for m in re.finditer(r"(?<![`\w/])([a-z0-9_]+)#([a-z0-9_]+)(?![\w`])", no_inline):
        if m.group(1) in ids and m.group(2) not in (fms.get(m.group(1), {}).get("_clauses") or []):
            err(f"reference to a clause that does not exist: {m.group(0)}")


def lint_contract(ctx, path, cid, ids, errors):
    """Check one contract. Return its front matter, or None if it has none."""
    def err(msg):
        errors.append(f"{cid}: {msg}")

    text = path.read_text(encoding="utf-8")
    fm, body = front_matter(text)
    if fm is None:
        err("no front matter")
        return None
    fm["_text"] = text
    if not NAME.match(cid):
        err("file name must be 1-3 words of a-z, 0-9, joined by `_`")
    name = fm.get("name", "")
    if not isinstance(name, str) or not name or len(name.split()) > 3:
        err("`name` is missing or longer than 3 words")
    for k in ("implements", "enforces"):
        if k not in fm or not isinstance(fm[k], list):
            err(f"`{k}` is missing (use `[]` for none)")
    implements = fm.get("implements") if isinstance(fm.get("implements"), list) else []
    enforces = fm.get("enforces") if isinstance(fm.get("enforces"), list) else []
    is_root = fm.get("root") == "yes"
    if is_root and implements:
        err("`root: yes` but `implements` is not empty")
    if not is_root and not implements:
        err("no `implements` and no `root: yes`: an orphan")
    for p in implements:
        if p not in ids:
            err(f"implements an unknown contract: {p}")
    if not enforces:
        err("`enforces` is empty: a contract always enforces something")
    paths = [e for e in enforces if is_path(e)]
    subs = [e for e in enforces if not is_path(e)]
    if paths and subs:
        err("`enforces` mixes files and contracts: a contract enforces one or the other")
    for p in paths:
        if not (ctx.root / p).exists():
            err(f"enforced path does not exist: {p}")
    for c in subs:
        if c not in ids:
            err(f"enforces an unknown contract: {c}")
    fm["_leaf"] = bool(paths) and not subs
    if len(text.splitlines()) > MAX_LINES or len(enforces) > MAX_ENFORCED:
        err(f"too large ({len(text.splitlines())} lines, {len(enforces)} enforced entries; limits {MAX_LINES} and {MAX_ENFORCED}): propose a new level")

    secs = sections(body)
    titles = [t for t, _ in secs]
    required = SECTIONS[:4]
    present = [t for t in titles if t in SECTIONS]
    expected = required + (["Notes"] if "Notes" in titles else [])
    if present != expected or any(t not in titles for t in required):
        err(f"sections must be {', '.join(SECTIONS[:4])} (then optional Notes) in this order; found: {', '.join(titles) or 'none'}")
        return fm
    content = dict(secs)
    for t in titles:
        if TODO in content[t]:
            err(f"section {t} is not written yet")

    view = content["View"]
    if not ("```" in view or re.search(r"^\s*\|\s*[-:]+", view, re.M)):
        err("View has no diagram, table or tree")

    clauses = []
    for row in table_rows(content["Clauses"]):
        n = row[0]
        if not NAME.match(n):
            err(f"clause name `{n}` must be 1-3 words of a-z, 0-9, joined by `_`")
        if n in clauses:
            err(f"duplicate clause name `{n}`")
        clauses.append(n)
    if not clauses:
        err("Clauses has no rows")
    fm["_clauses"] = clauses

    types, seen, vfiles, rows = ctx.types(), {}, [], {}
    for row in table_rows(content["Verification"]):
        if len(row) < 4:
            err("Verification rows need Name, Type, Proves, File")
            continue
        n, typ, _, file = row[:4]
        seen[n] = seen.get(n, 0) + 1
        rows[n] = (typ, file)
        if n not in clauses:
            err(f"verification row for unknown clause `{n}`")
        if typ not in types:
            err(f"`{n}`: type `{typ}` is not in {sorted(types)}")
        if typ == "covered-by":
            if fm["_leaf"]:
                err(f"`{n}`: a contract that enforces files cannot use `covered-by`")
            refs = [r.strip().strip("`") for r in file.split(",") if r.strip()]
            if not refs:
                err(f"`{n}`: `covered-by` must list the clauses that cover it")
            fm.setdefault("_covers", []).extend((n, r) for r in refs)
        elif not (ctx.tests / file).exists():
            err(f"`{n}`: verification file missing: {file}")
        else:
            vfiles.append(file)
    for n in clauses:
        if seen.get(n, 0) != 1:
            err(f"clause `{n}` needs exactly one verification row (found {seen.get(n, 0)})")
    fm["_rows"], fm["_vfiles"] = rows, vfiles
    return fm


def lint_graph(fms, errors):
    """Symmetry, cycles, covered-by references. Return the level of every contract."""
    for cid, fm in fms.items():
        for p in fm.get("implements") or []:
            if p in fms and cid not in (fms[p].get("enforces") or []):
                errors.append(f"{cid}: implements {p}, but {p} does not enforce {cid}")
        for c in fm.get("enforces") or []:
            if not is_path(c) and c in fms and cid not in (fms[c].get("implements") or []):
                errors.append(f"{cid}: enforces {c}, but {c} does not implement {cid}")
        children = {c for c in fm.get("enforces") or [] if not is_path(c)}
        for n, ref in fm.get("_covers", []):
            m = re.match(r"^([a-z0-9_]+)#([a-z0-9_]+)$", ref)
            if not m or m.group(1) not in children or m.group(2) not in (fms[m.group(1)].get("_clauses") or []):
                errors.append(f"{cid}: `{n}` is covered-by `{ref}`, which is not a clause of an enforced contract")
    level, state = {}, {}

    def visit(c, chain):
        if state.get(c) == 2:
            return level[c]
        if state.get(c) == 1:
            errors.append("cycle: " + " -> ".join(chain[chain.index(c):] + [c]))
            return 0
        state[c] = 1
        ps = [p for p in fms[c].get("implements") or [] if p in fms]
        level[c] = 1 + max([visit(p, chain + [c]) for p in ps], default=0)
        state[c] = 2
        return level[c]

    for c in fms:
        visit(c, [])
    return level


def stale_verifications(ctx, fms, errors):
    """Files in tests/<contract id>/ that no Verification row cites."""
    for cid, fm in fms.items():
        folder = ctx.tests / cid
        if not folder.is_dir():
            continue
        cited = {Path(f).as_posix() for f in fm.get("_vfiles", [])}
        for f in sorted(folder.rglob("*")):
            if f.is_file():
                r = f.relative_to(ctx.tests).as_posix()
                if r not in cited and "__pycache__" not in r:
                    errors.append(f"{cid}: stale verification file, no clause cites it: {r}")


def project_files(ctx):
    try:
        out = subprocess.run(["git", "ls-files"], cwd=ctx.root, capture_output=True, text=True, check=True).stdout
        return sorted(l for l in out.splitlines() if l)
    except (OSError, subprocess.CalledProcessError):
        skip = {".git", "node_modules", "__pycache__"}
        found = []
        for dp, dn, fn in os.walk(ctx.root):
            dn[:] = [d for d in dn if d not in skip]
            found += [Path(dp, f).relative_to(ctx.root).as_posix() for f in fn]
        return sorted(found)


def under(f, p):
    p = (p[2:] if p.startswith("./") else p).rstrip("/")
    return f == p or f.startswith(p + "/")


def coverage(ctx, fms):
    """Files of the contracted domain that no leaf contract enforces."""
    domain = ctx.paths_setting("Contracted domain")
    if domain is None or not domain:
        return None
    excluded = (ctx.paths_setting("Excluded") or []) + [rel(ctx.ws, ctx.root), rel(ctx.tests, ctx.root)]
    governed = [e for fm in fms.values() if fm.get("_leaf") for e in fm.get("enforces") or []]
    zones = []
    for f in project_files(ctx):
        if any(under(f, d) for d in domain) and not any(under(f, x) for x in excluded):
            if not any(under(f, g) for g in governed):
                zones.append(f)
    return zones


def write_links(ctx, fms, level):
    """Regenerate the links block in every contract, and INDEX.md."""
    base = ctx.base

    def link(c):
        return f"[{c}]({c}.md)" if c in fms else c

    def flink(p):
        return f"[`{p}`]({rel(ctx.root / p, base)})"

    for cid, fm in fms.items():
        up = ", ".join(link(p) for p in fm.get("implements") or []) or "none (root)"
        down = ", ".join(flink(e) if is_path(e) else link(e) for e in fm.get("enforces") or []) or "none"
        ver = []
        for n, (typ, file) in (fm.get("_rows") or {}).items():
            if typ == "covered-by":
                ver.append(f"`{n}` covered by " + ", ".join(sorted({f"[{r.split('#')[0]}]({r.split('#')[0]}.md)" for r in re.split(r"[,\s]+", file) if '#' in r})))
            else:
                ver.append(f"[`{file}`]({rel(ctx.tests / file, base)})")
        block = (f"{START}\n> **Level** {level.get(cid, '?')} · **Implements:** {up}\n> **Enforces:** {down}\n"
                 f"> **Verified by:** {' · '.join(ver) or 'nothing yet'}\n{END}")
        f = ctx.cpath(cid)
        text = f.read_text(encoding="utf-8")
        if START in text and END in text:
            new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, count=1, flags=re.S)
        else:
            new = re.sub(r"^(# .*\n)", lambda m: m.group(1) + "\n" + block + "\n", text, count=1, flags=re.M)
        if new != text:
            f.write_text(new, encoding="utf-8")

    lines = ["# Contract index", "", "<!-- generated by contract-tools lint, do not edit -->", "", "```mermaid", "flowchart TD"]
    for cid, fm in sorted(fms.items()):
        lines.append(f'    {cid}["{fm.get("name", cid)}"]')
    for cid, fm in sorted(fms.items()):
        for p in fm.get("implements") or []:
            lines.append(f"    {p} --> {cid}")
    lines += ["```", "", "| Level | Contract | Kind |", "|---|---|---|"]
    for cid, fm in sorted(fms.items(), key=lambda kv: (level.get(kv[0], 0), kv[0])):
        kind = "root" if fm.get("root") == "yes" else ("leaf" if fm.get("_leaf") else "intermediate")
        lines.append(f"| {level.get(cid, '?')} | {link(cid)} | {kind} |")
    lines += ["", "| File | Enforced by (leaf contracts) |", "|---|---|"]
    byfile = {}
    for cid, fm in fms.items():
        if fm.get("_leaf"):
            for e in fm.get("enforces") or []:
                byfile.setdefault(e, []).append(link(cid))
    for e in sorted(byfile):
        lines.append(f"| {flink(e)} | {', '.join(byfile[e])} |")
    (base / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


