#!/usr/bin/env python3
"""Check that contracts and tickets follow the contract-flow template.

Usage: python3 -I contract-lint.py <workspace> <tests folder> [--root DIR] [--types a,b]

Checks only the rigid parts (header, graph, sections, names, verification rows, tickets).
It also regenerates, in every contract, the links block between the
`contract-links` markers, and `contracts/INDEX.md` (map, levels, file -> contract).
Exit code 0 when everything conforms, 1 otherwise. Standard library only.
"""
import argparse
import re
import sys
from pathlib import Path

TYPES = {"unit", "interface", "integration", "end-to-end", "script", "ai-check", "covered-by"}
SECTIONS = ["Purpose", "View", "Clauses", "Verification", "Notes"]
NAME = re.compile(r"^[a-z0-9]+(_[a-z0-9]+){0,2}$")
START = "<!-- contract-links:start (generated by contract-lint, do not edit) -->"
END = "<!-- contract-links:end -->"


def is_path(entry):
    """A file or folder path contains `/` or `.`; anything else is a contract ID."""
    return "/" in entry or "." in entry


def front_matter(text):
    """Return (dict, body). Handles `key: value`, inline lists and `- item` lists."""
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        return None, text
    data, key = {}, None
    for line in m.group(1).splitlines():
        line = re.sub(r"\s+#.*$", "", line).rstrip()
        if not line.strip():
            continue
        item = re.match(r"^\s+-\s+(.*)$", line)
        if item and key:
            data.setdefault(key, []).append(item.group(1).strip())
            continue
        kv = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if kv:
            key, val = kv.group(1), kv.group(2).strip()
            if val.startswith("[") and val.endswith("]"):
                data[key] = [v.strip() for v in val[1:-1].split(",") if v.strip()]
            elif val:
                data[key] = val
            else:
                data[key] = []
    return data, m.group(2)


def sections(body):
    """Return the list of (title, content) for top-level `## ` headings, ignoring code blocks."""
    out, cur, in_code = [], None, False
    for line in body.splitlines():
        if line.startswith("```") or line.startswith("~~~"):
            in_code = not in_code
        if not in_code and line.startswith("## "):
            cur = [line[3:].strip(), []]
            out.append(cur)
        elif cur is not None:
            cur[1].append(line)
    return [(t, "\n".join(c)) for t, c in out]


def table_rows(content):
    rows = []
    for line in content.splitlines():
        line = line.strip()
        if line.startswith("|") and not re.match(r"^\|[\s:|-]+\|?$", line):
            rows.append([c.strip().strip("`") for c in line.strip("|").split("|")])
    return rows[1:] if rows else []  # drop header


def lint_contract(path, cid, root, tests, types, ids, errors):
    """Check one contract. Return its front matter, or None if it has none."""
    def err(msg):
        errors.append(f"{cid}: {msg}")

    fm, body = front_matter(path.read_text(encoding="utf-8"))
    if fm is None:
        err("no front matter")
        return None
    if not NAME.match(cid):
        err("file name must be 1-3 words of a-z, 0-9, joined by `_`")
    name = fm.get("name", "")
    if not isinstance(name, str) or not name or len(name.split()) > 3:
        err("`name` is missing or longer than 3 words")
    for k in ("implements", "enforces"):
        if k not in fm or not isinstance(fm[k], list):
            err(f"`{k}` is missing (use `[]` for none)")
    implements = fm.get("implements") if isinstance(fm.get("implements"), list) else []
    enforces = fm.get("enforces") if isinstance(fm.get("enforces"), list) else []
    is_root = fm.get("root") == "yes"
    if is_root and implements:
        err("`root: yes` but `implements` is not empty")
    if not is_root and not implements:
        err("no `implements` and no `root: yes`: an orphan")
    for p in implements:
        if p not in ids:
            err(f"implements an unknown contract: {p}")
    if not enforces:
        err("`enforces` is empty: a contract always enforces something")
    paths = [e for e in enforces if is_path(e)]
    subs = [e for e in enforces if not is_path(e)]
    if paths and subs:
        err("`enforces` mixes files and contracts: a contract enforces one or the other")
    for p in paths:
        if not (root / p).exists():
            err(f"enforced path does not exist: {p}")
    for c in subs:
        if c not in ids:
            err(f"enforces an unknown contract: {c}")
    fm["_leaf"] = bool(paths) and not subs

    secs = sections(body)
    titles = [t for t, _ in secs]
    required = SECTIONS[:4]
    present = [t for t in titles if t in SECTIONS]
    expected = required + (["Notes"] if "Notes" in titles else [])
    if present != expected or any(t not in titles for t in required):
        err(f"sections must be {', '.join(SECTIONS[:4])} (then optional Notes) in this order; found: {', '.join(titles) or 'none'}")
        return fm
    content = dict(secs)

    view = content["View"]
    if not ("```" in view or re.search(r"^\s*\|\s*[-:]+", view, re.M)):
        err("View has no diagram, table or tree")

    clauses = []
    for row in table_rows(content["Clauses"]):
        n = row[0]
        if not NAME.match(n):
            err(f"clause name `{n}` must be 1-3 words of a-z, 0-9, joined by `_`")
        if n in clauses:
            err(f"duplicate clause name `{n}`")
        clauses.append(n)
    if not clauses:
        err("Clauses has no rows")

    fm["_clauses"] = clauses
    seen = {}
    for row in table_rows(content["Verification"]):
        if len(row) < 4:
            err("Verification rows need Name, Type, Proves, File")
            continue
        n, typ, _, file = row[:4]
        seen[n] = seen.get(n, 0) + 1
        if n not in clauses:
            err(f"verification row for unknown clause `{n}`")
        if typ not in types:
            err(f"`{n}`: type `{typ}` is not in {sorted(types)}")
        if typ == "covered-by":
            if fm["_leaf"]:
                err(f"`{n}`: a contract that enforces files cannot use `covered-by`")
            refs = [r.strip().strip("`") for r in file.split(",") if r.strip()]
            if not refs:
                err(f"`{n}`: `covered-by` must list the clauses that cover it")
            fm.setdefault("_covers", []).extend((n, r) for r in refs)
        elif not (tests / file).exists():
            err(f"`{n}`: verification file missing: {file}")
    for n in clauses:
        if seen.get(n, 0) != 1:
            err(f"clause `{n}` needs exactly one verification row (found {seen.get(n, 0)})")
    return fm


def lint_graph(fms, errors):
    """Symmetry, cycles, covered-by references. Return the level of every contract."""
    for cid, fm in fms.items():
        for p in fm.get("implements") or []:
            if p in fms and cid not in (fms[p].get("enforces") or []):
                errors.append(f"{cid}: implements {p}, but {p} does not enforce {cid}")
        for c in fm.get("enforces") or []:
            if not is_path(c) and c in fms and cid not in (fms[c].get("implements") or []):
                errors.append(f"{cid}: enforces {c}, but {c} does not implement {cid}")
        children = {c for c in fm.get("enforces") or [] if not is_path(c)}
        for n, ref in fm.get("_covers", []):
            m = re.match(r"^([a-z0-9_]+)#([a-z0-9_]+)$", ref)
            if not m or m.group(1) not in children or m.group(2) not in (fms[m.group(1)].get("_clauses") or []):
                errors.append(f"{cid}: `{n}` is covered-by `{ref}`, which is not a clause of an enforced contract")
    level, state = {}, {}

    def visit(c, chain):
        if state.get(c) == 2:
            return level[c]
        if state.get(c) == 1:
            errors.append("cycle: " + " -> ".join(chain[chain.index(c):] + [c]))
            return 0
        state[c] = 1
        ps = [p for p in fms[c].get("implements") or [] if p in fms]
        level[c] = 1 + max([visit(p, chain + [c]) for p in ps], default=0)
        state[c] = 2
        return level[c]

    for c in fms:
        visit(c, [])
    return level


def write_links(base, fms, level):
    """Regenerate the links block in every contract, and INDEX.md."""
    def link(c):
        return f"[{c}]({c}.md)" if c in fms else c

    for cid, fm in fms.items():
        up = ", ".join(link(p) for p in fm.get("implements") or []) or "none (root)"
        down = ", ".join(f"`{e}`" if is_path(e) else link(e) for e in fm.get("enforces") or []) or "none"
        block = f"{START}\n> **Level** {level.get(cid, '?')} · **Implements:** {up}\n> **Enforces:** {down}\n{END}"
        f = base / f"{cid}.md"
        text = f.read_text(encoding="utf-8")
        if START in text and END in text:
            new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, count=1, flags=re.S)
        else:
            new = re.sub(r"^(# .*\n)", lambda m: m.group(1) + "\n" + block + "\n", text, count=1, flags=re.M)
        if new != text:
            f.write_text(new, encoding="utf-8")

    lines = ["# Contract index", "", "<!-- generated by contract-lint, do not edit -->", "",
             "```mermaid", "flowchart TD"]
    for cid, fm in sorted(fms.items()):
        lines.append(f'    {cid}["{fm.get("name", cid)}"]')
    for cid, fm in sorted(fms.items()):
        for p in fm.get("implements") or []:
            lines.append(f"    {p} --> {cid}")
    lines += ["```", "", "| Level | Contract | Kind |", "|---|---|---|"]
    for cid, fm in sorted(fms.items(), key=lambda kv: (level.get(kv[0], 0), kv[0])):
        kind = "root" if fm.get("root") == "yes" else ("leaf" if fm.get("_leaf") else "intermediate")
        lines.append(f"| {level.get(cid, '?')} | {link(cid)} | {kind} |")
    lines += ["", "| File | Enforced by (leaf contracts) |", "|---|---|"]
    byfile = {}
    for cid, fm in fms.items():
        if fm.get("_leaf"):
            for e in fm.get("enforces") or []:
                byfile.setdefault(e, []).append(link(cid))
    for e in sorted(byfile):
        lines.append(f"| `{e}` | {', '.join(byfile[e])} |")
    (base / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def lint_tickets(folder, errors):
    names = set()
    for f in sorted(folder.glob("*.md")):
        stem = f.stem
        m = re.match(r"^T-(.+)$", stem)
        if not m or not NAME.match(m.group(1)):
            errors.append(f"ticket {f.name}: must be T-<1-3 words of a-z, 0-9 joined by _>")
            continue
        if stem in names:
            errors.append(f"ticket {stem}: duplicate")
        names.add(stem)
        fm, _ = front_matter(f.read_text(encoding="utf-8"))
        if fm is None:
            errors.append(f"ticket {stem}: no front matter")
            continue
        if fm.get("id") != stem:
            errors.append(f"ticket {stem}: `id` differs from file name")
        for k in ("status", "direction", "contract", "clause"):
            if not fm.get(k):
                errors.append(f"ticket {stem}: `{k}` missing")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("workspace")
    ap.add_argument("tests")
    ap.add_argument("--root", default=".")
    ap.add_argument("--types", default="")
    a = ap.parse_args()
    ws, tests, root = Path(a.workspace), Path(a.tests), Path(a.root)
    types = TYPES | {t for t in a.types.split(",") if t}
    errors = []
    base = ws / "contracts"
    files = [f for f in sorted(base.rglob("*.md")) if f.name != "INDEX.md"]
    ids = {f.relative_to(base).with_suffix("").as_posix() for f in files}
    fms = {}
    for f in files:
        cid = f.relative_to(base).with_suffix("").as_posix()
        if "/" in cid:
            errors.append(f"{cid}: contracts live directly in contracts/, without subfolders")
        fm = lint_contract(f, cid, root, tests, types, ids, errors)
        if fm is not None:
            fms[cid] = fm
    level = lint_graph(fms, errors)
    write_links(base, fms, level)
    if (ws / "tickets").is_dir():
        lint_tickets(ws / "tickets", errors)
    for e in errors:
        print("FAIL", e)
    print(f"{len(files)} contracts checked, {len(errors)} problems")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
