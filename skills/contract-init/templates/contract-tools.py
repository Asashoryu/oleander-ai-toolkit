#!/usr/bin/env python3
"""contract-tools: the deterministic side of contract-flow.

Run from the project root, from the tests folder where this file lives:

    python3 -I <tests folder>/contract-tools.py [--workspace DIR] [--root DIR] <command> ...

Commands
    lint                          check every contract and ticket, regenerate links blocks and INDEX.md
    verify [--contract ID ...]    run every scripted verification, report ai-check and covered-by as to judge
    ticket new|log|status|direction|reopen|list|sweep
    clause add|rename|remove      edit the Clauses and Verification tables and the verification files
    edge add|remove               write an implements/enforces edge on both sides
    files add|remove              add or remove a file in the `enforces` of a leaf contract
    contract new|rename           create a skeleton, or rename a contract everywhere
    root set|unset                mark a contract as a root
    scope add|clear|list          the contracts and files touched in this flow (scope.txt)
    summary                       the state of the flow in a few lines
    handoff                       write the handoff file

Agents write prose (Purpose, View, Notes, ticket text). Everything structured goes through
this tool; every command that edits ends by running the lint on the result.
Exit code 0 when everything conforms, 1 otherwise. Standard library only.
"""
import argparse
import os
import re
import shlex
import subprocess
import sys
from datetime import datetime
from pathlib import Path

TYPES = {"unit", "interface", "integration", "end-to-end", "script", "ai-check", "covered-by"}
SCRIPT_TYPES_NOT = {"ai-check", "covered-by"}
SECTIONS = ["Purpose", "View", "Clauses", "Verification", "Notes"]
NAME = re.compile(r"^[a-z0-9]+(_[a-z0-9]+){0,2}$")
START = "<!-- contract-links:start (generated by contract-tools lint, do not edit) -->"
END = "<!-- contract-links:end -->"
TODO = "_to be written_"
STUB = "not written yet"
MAX_LINES, MAX_ENFORCED = 300, 15

STATUSES = {"open", "resolved", "rerouted", "obsolete"}
DIRECTIONS = {"code", "contract", "escalate"}
EVENTS = {"opened", "direction_changed", "status_changed", "reopened", "note"}
TRANSITIONS = {"open": {"resolved", "rerouted", "obsolete"}, "resolved": set(), "obsolete": set(),
               "rerouted": {"resolved", "obsolete"}}
REOPENABLE = {"resolved", "obsolete", "rerouted"}
TICKET_SECTIONS = ["Problem", "Conflict", "Verification", "Proposed direction", "Log"]
LOG_LINE = re.compile(r"^- (\d{4}-\d\d-\d\dT\d\d:\d\d) · ([A-Za-z0-9_.-]+) · ([a-z_]+) · (.*)$")


# --------------------------------------------------------------------------- parsing

def is_path(entry):
    """A file or folder path contains `/` or `.`; anything else is a contract ID."""
    return "/" in entry or "." in entry


def front_matter(text):
    """Return (dict, body). Handles `key: value`, inline lists and `- item` lists."""
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        return None, text
    data, key = {}, None
    for line in m.group(1).splitlines():
        line = re.sub(r"\s+#.*$", "", line).rstrip()
        if not line.strip():
            continue
        item = re.match(r"^\s+-\s+(.*)$", line)
        if item and key:
            data.setdefault(key, []).append(item.group(1).strip())
            continue
        kv = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if kv:
            key, val = kv.group(1), kv.group(2).strip()
            if val.startswith("[") and val.endswith("]"):
                data[key] = [v.strip() for v in val[1:-1].split(",") if v.strip()]
            elif val:
                data[key] = val
            else:
                data[key] = []
    return data, m.group(2)


def sections(body):
    """List of (title, content) for top-level `## ` headings, ignoring code blocks."""
    out, cur, in_code = [], None, False
    for line in body.splitlines():
        if line.startswith("```") or line.startswith("~~~"):
            in_code = not in_code
        if not in_code and line.startswith("## "):
            cur = [line[3:].strip(), []]
            out.append(cur)
        elif cur is not None:
            cur[1].append(line)
    return [(t, "\n".join(c)) for t, c in out]


def table_rows(content):
    rows = []
    for line in content.splitlines():
        line = line.strip()
        if line.startswith("|") and not re.match(r"^\|[\s:|-]+\|?$", line):
            rows.append([c.strip().strip("`") for c in line.strip("|").split("|")])
    return rows[1:] if rows else []


def strip_fences(text):
    out, in_code = [], False
    for line in text.splitlines():
        if line.startswith("```") or line.startswith("~~~"):
            in_code = not in_code
            continue
        if not in_code:
            out.append(line)
    return "\n".join(out)


def prose(text):
    """Text to scan for references: no generated block, no code blocks, no front matter."""
    text = re.sub(re.escape(START) + r".*?" + re.escape(END), "", text, flags=re.S)
    _, body = front_matter(text)
    return strip_fences(body)


def slug(heading):
    s = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return s.replace(" ", "-")


def anchors(path):
    try:
        return {slug(m.group(1)) for m in re.finditer(r"^#{1,6}\s+(.*?)\s*$", strip_fences(path.read_text(encoding="utf-8")), re.M)}
    except OSError:
        return set()


# --------------------------------------------------------------------------- context

class Ctx:
    def __init__(self, workspace, root, tests):
        self.root, self.tests = root, tests
        self.ws = workspace
        self.base = workspace / "contracts"
        self.tix = workspace / "tickets"
        self.config = self.read_config()

    def read_config(self):
        readme = self.ws / "README.md"
        cfg = {}
        if readme.exists():
            sec = dict(sections(readme.read_text(encoding="utf-8"))).get("Configuration", "")
            for row in table_rows(sec):
                if len(row) >= 2:
                    cfg[row[0].strip("*` ")] = row[1].strip()
        return cfg

    def types(self):
        extra = self.config.get("Extra verification types", "")
        if "{{" in extra or extra.lower() in ("", "none"):
            return set(TYPES)
        return TYPES | {t.strip("` ") for t in re.split(r"[,\s]+", extra) if t.strip("` ")}

    def paths_setting(self, key):
        v = self.config.get(key, "")
        if "{{" in v or v.lower() in ("", "none"):
            return None if "{{" in v else []
        found = re.findall(r"`([^`]+)`", v)
        return found or [p.strip() for p in v.split(",") if p.strip()]

    def runner(self):
        v = self.config.get("Script runner", "").strip().strip("`")
        return shlex.split(v) if v and "{{" not in v else None

    def cpath(self, cid):
        return self.base / f"{cid}.md"

    def contract_ids(self):
        if not self.base.is_dir():
            return []
        return sorted(f.stem for f in self.base.glob("*.md") if f.name != "INDEX.md")


def find_workspace(root, given):
    if given:
        return Path(given)
    for name in ("CLAUDE.md", "AGENTS.md"):
        f = root / name
        if f.exists():
            m = re.search(r"^Contract-flow workspace:\s*(\S+)", f.read_text(encoding="utf-8"), re.M)
            if m:
                return root / m.group(1)
    sys.exit("contract-tools: no workspace. Add `Contract-flow workspace: <path>` to CLAUDE.md or pass --workspace.")


def rel(target, start):
    return Path(os.path.relpath(target, start)).as_posix()


