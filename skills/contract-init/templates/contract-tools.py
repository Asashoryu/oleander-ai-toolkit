def now():
    return datetime.now().strftime("%Y-%m-%dT%H:%M")


def tpath(ctx, tid):
    tid = tid if tid.startswith("T-") else f"T-{tid}"
    return ctx.tix / f"{tid}.md", tid


def load_ticket(ctx, tid):
    p, tid = tpath(ctx, tid)
    if not p.exists():
        sys.exit(f"no ticket {tid}")
    text = p.read_text(encoding="utf-8")
    fm, body = front_matter(text)
    return p, tid, text, fm, body


def set_field(text, key, value):
    return re.sub(rf"^{key}:.*$", f"{key}: {value}", text, count=1, flags=re.M)


def append_log(text, actor, event, detail):
    line = f"- {now()} · {actor} · {event} · {detail}"
    return text.rstrip("\n") + "\n" + line + "\n"


def need_reason(a):
    if not a.reason or not a.reason.strip():
        sys.exit("a reason is required (--reason)")


def find_ticket_for(ctx, contract, clause):
    for f in ticket_files(ctx):
        fm, _ = front_matter(f.read_text(encoding="utf-8"))
        if fm and fm.get("contract") == contract and fm.get("clause") == clause:
            return f
    return None


def change_status(ctx, tid, new, actor, reason):
    p, tid, text, fm, _ = load_ticket(ctx, tid)
    old = fm["status"]
    if new == "open":
        if old not in REOPENABLE:
            sys.exit(f"{tid} is {old}: nothing to reopen")
        text = append_log(text, actor, "reopened", reason)
    else:
        if new not in TRANSITIONS.get(old, set()):
            sys.exit(f"{tid}: {old} -> {new} is not allowed")
        text = append_log(text, actor, "status_changed", f"{old} -> {new}: {reason}")
    p.write_text(set_field(text, "status", new), encoding="utf-8")
    return tid


def change_direction(ctx, tid, new, actor, reason):
    p, tid, text, fm, _ = load_ticket(ctx, tid)
    if new not in DIRECTIONS:
        sys.exit(f"direction must be one of {sorted(DIRECTIONS)}")
    old = fm["direction"]
    if old != new:
        text = append_log(text, actor, "direction_changed", f"{old} -> {new}: {reason}")
        p.write_text(set_field(text, "direction", new), encoding="utf-8")
    return tid


def new_ticket(ctx, name, contract, clause, direction, actor, reason, texts):
    ids = set(ctx.contract_ids())
    if contract not in ids:
        sys.exit(f"unknown contract {contract}")
    fm, _ = front_matter(ctx.cpath(contract).read_text(encoding="utf-8"))
    _, fms, _ = load_all(ctx)
    if clause not in (fms.get(contract, {}).get("_clauses") or []):
        sys.exit(f"{contract} has no clause {clause}: add it first (`clause add ... --ticket {name}`)")
    existing = find_ticket_for(ctx, contract, clause)
    if existing:
        f2, _ = front_matter(existing.read_text(encoding="utf-8"))
        if f2["status"] == "open":
            print(f"{existing.stem} is already open on {contract}#{clause}")
            return existing.stem
        change_status(ctx, existing.stem, "open", actor, reason)
        change_direction(ctx, existing.stem, direction, actor, reason)
        print(f"{existing.stem} reopened")
        return existing.stem
    if not NAME.match(name):
        sys.exit("ticket name must be 1-3 words of a-z, 0-9, joined by _")
    tid = f"T-{name}"
    p = ctx.tix / f"{tid}.md"
    if p.exists():
        sys.exit(f"{tid} exists: reword the name")
    ctx.tix.mkdir(parents=True, exist_ok=True)
    problem, conflict, verification, proposal = [texts.get(k) or TODO for k in ("problem", "conflict", "verification", "proposal")]
    p.write_text(
        f"---\nid: {tid}\nstatus: open\ndirection: {direction}\ncontract: {contract}\nclause: {clause}\n---\n\n"
        f"# {texts.get('title') or name.replace('_', ' ')}\n\n## Problem\n{problem}\n\n## Conflict\n{conflict}\n\n"
        f"## Verification\n{verification}\n\n## Proposed direction\n{proposal}\n\n## Log\n"
        f"- {now()} · {actor} · opened · {direction}: {reason}\n", encoding="utf-8")
    print(f"opened {tid}")
    return tid


def cmd_ticket(ctx, a):
    c = a.tcmd
    if c == "new":
        new_ticket(ctx, a.name, a.contract, a.clause, a.direction, a.actor, a.reason,
                   {"title": a.title, "problem": a.problem, "conflict": a.conflict,
                    "verification": a.verification, "proposal": a.proposal})
    elif c == "log":
        p, tid, text, _, _ = load_ticket(ctx, a.id)
        p.write_text(append_log(text, a.actor, "note", a.detail), encoding="utf-8")
    elif c == "status":
        need_reason(a)
        print(change_status(ctx, a.id, a.new, a.actor, a.reason), "->", a.new)
    elif c == "direction":
        need_reason(a)
        print(change_direction(ctx, a.id, a.new, a.actor, a.reason), "->", a.new)
    elif c == "reopen":
        need_reason(a)
        print(change_status(ctx, a.id, "open", a.actor, a.reason), "reopened")
    elif c == "list":
        for f in ticket_files(ctx):
            fm, _ = front_matter(f.read_text(encoding="utf-8"))
            if fm and (not a.status or fm.get("status") == a.status) and (not a.direction or fm.get("direction") == a.direction):
                print(f"{fm['id']}  {fm['status']}  {fm['direction']}  {fm['contract']}#{fm['clause']}")
    elif c == "sweep":
        sweep(ctx, a)
        return run_lint(ctx)[0] and 1 or 0
    if c in ("new", "log", "status", "direction", "reopen"):
        return 1 if run_lint(ctx)[0] else 0
    return 0


def sweep(ctx, a):
    ids, fms, _ = load_all(ctx)
    for f in ticket_files(ctx):
        fm, _ = front_matter(f.read_text(encoding="utf-8"))
        if not fm:
            continue
        tid, c, k, st = fm["id"], fm.get("contract"), fm.get("clause"), fm.get("status")
        exists = c in fms and k in (fms[c].get("_clauses") or [])
        if st in ("open", "rerouted") and not exists:
            change_status(ctx, tid, "obsolete", "sweep", f"{c}#{k} no longer exists")
            print(f"{tid}: obsolete ({c}#{k} no longer exists)")
            continue
        if not exists or a.no_run:
            continue
        typ = (fms[c].get("_rows") or {}).get(k, (None,))[0]
        if typ in SCRIPT_TYPES_NOT or typ is None:
            continue
        if st == "open" and fm.get("direction") == "code":
            res, _ = verify_clause(ctx, fms[c], c, k)
            if res == "PASS":
                change_status(ctx, tid, "resolved", "sweep", f"the verification of {c}#{k} passes")
                print(f"{tid}: resolved (verification passes)")
        elif st == "resolved":
            res, note = verify_clause(ctx, fms[c], c, k)
            if res == "FAIL":
                change_status(ctx, tid, "open", "sweep", f"the verification of {c}#{k} fails again: {note}")
                change_direction(ctx, tid, "code", "sweep", "the clause fails again")
                print(f"{tid}: reopened (verification fails again)")


