def section_span(lines, title):
    """(start, end) line indexes of the body of `## title`, ignoring code blocks."""
    in_code, start = False, None
    for i, line in enumerate(lines):
        if line.startswith("```") or line.startswith("~~~"):
            in_code = not in_code
        if not in_code and line.startswith("## "):
            if start is not None:
                return start, i
            if line[3:].strip() == title:
                start = i + 1
    return (start, len(lines)) if start is not None else (None, None)


def add_table_row(text, title, row):
    lines = text.split("\n")
    s, e = section_span(lines, title)
    if s is None:
        sys.exit(f"no section {title}")
    last = None
    for i in range(s, e):
        if lines[i].strip().startswith("|"):
            last = i
    if last is None:
        sys.exit(f"section {title} has no table")
    lines.insert(last + 1, row)
    return "\n".join(lines)


def drop_table_row(text, title, name):
    lines = text.split("\n")
    s, e = section_span(lines, title)
    if s is None:
        return text
    keep = [l for i, l in enumerate(lines) if not (s <= i < e and l.strip().startswith("|") and re.match(rf"^\|\s*`?{re.escape(name)}`?\s*\|", l.strip()))]
    return "\n".join(keep)


def set_list(text, key, items):
    """Rewrite a list field of the front matter."""
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    head = m.group(1)
    if key == "enforces":
        new = f"{key}:" + "".join(f"\n  - {i}" for i in items) if items else f"{key}: []"
    else:
        new = f"{key}: [{', '.join(items)}]"
    pat = re.compile(rf"^{key}:.*(?:\n[ \t]+-.*)*", re.M)
    head2 = pat.sub(lambda _: new, head, count=1) if pat.search(head) else head + "\n" + new
    return "---\n" + head2 + "\n---\n" + text[m.end():]


def set_flag(text, on):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    head = re.sub(r"^root:.*\n?", "", m.group(1), flags=re.M).rstrip("\n")
    if on:
        lines = head.split("\n")
        head = "\n".join([lines[0], "root: yes"] + lines[1:])
    return "---\n" + head + "\n---\n" + text[m.end():]


def read_fm(ctx, cid):
    p = ctx.cpath(cid)
    if not p.exists():
        sys.exit(f"unknown contract {cid}")
    text = p.read_text(encoding="utf-8")
    fm, _ = front_matter(text)
    return p, text, fm


def finish(ctx):
    errors, zones, _, _ = run_lint(ctx, quiet=True)
    for e in errors:
        print("FAIL", e)
    print(f"lint: {len(errors)} problems")
    return 1 if errors else 0


def cmd_clause(ctx, a):
    p, text, fm = read_fm(ctx, a.contract)
    _, fms, _ = load_all(ctx)
    clauses = fms.get(a.contract, {}).get("_clauses") or []
    rows = fms.get(a.contract, {}).get("_rows") or {}
    if a.ccmd == "add":
        if not NAME.match(a.name):
            sys.exit("clause name must be 1-3 words of a-z, 0-9, joined by _")
        if a.name in clauses:
            sys.exit(f"{a.contract} already has a clause {a.name}")
        if a.type not in ctx.types():
            sys.exit(f"type must be one of {sorted(ctx.types())}")
        if a.type == "covered-by":
            if not a.covers:
                sys.exit("--covers is required for covered-by: a comma separated list of <contract>#<clause>")
            target = a.covers
        else:
            ext = ext_for(ctx, a.file) if a.type != "ai-check" else ".md"
            if a.file:
                target = a.file
            elif ext:
                target = f"{a.contract}/{a.name}{ext}"
            else:
                sys.exit("cannot choose a file extension: pass --file or set the Script runner")
            dest = ctx.tests / target
            if not dest.exists():
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(stub_text(Path(target).suffix, f"{a.contract}#{a.name}"), encoding="utf-8")
                print(f"created the stub {target} (it fails until it is written)")
        text = add_table_row(text, "Clauses", f"| `{a.name}` | {a.text} |")
        text = add_table_row(text, "Verification", f"| `{a.name}` | {a.type} | {a.proves or a.text} | `{target}` |")
        p.write_text(text, encoding="utf-8")
        if a.ticket:
            vf = f"`{target}`" if a.type == "covered-by" else f"[`{target}`]({rel(ctx.tests / target, ctx.tix)})"
            new_ticket(ctx, a.ticket, a.contract, a.name, "code", a.actor, a.reason or "clause added, nothing satisfies it yet", {
                "problem": f"The clause `{a.name}` was added to [{a.contract}]({rel(ctx.cpath(a.contract), ctx.tix)}) and nothing satisfies it yet.",
                "conflict": f"- [{a.contract}]({rel(ctx.cpath(a.contract), ctx.tix)}): \"{a.text}\"\n- the enforced files do not satisfy it yet",
                "verification": f"{vf} is a stub that fails until it is written.",
                "proposal": "code: write the code that satisfies the clause, and the verification."})
    elif a.ccmd == "rename":
        if a.old not in clauses:
            sys.exit(f"{a.contract} has no clause {a.old}")
        if not NAME.match(a.new) or a.new in clauses:
            sys.exit("the new name must be 1-3 words of a-z, 0-9, joined by _, and unused in the contract")
        typ, file = rows.get(a.old, (None, ""))
        new_file = file
        if typ and typ != "covered-by" and Path(file).stem == a.old:
            new_file = str(Path(file).with_name(a.new + Path(file).suffix).as_posix())
            src, dst = ctx.tests / file, ctx.tests / new_file
            if src.exists():
                dst.parent.mkdir(parents=True, exist_ok=True)
                src.rename(dst)
                if dst.suffix == ".md":
                    dst.write_text(dst.read_text(encoding="utf-8").replace(f"{a.contract}#{a.old}", f"{a.contract}#{a.new}"), encoding="utf-8")
        text = re.sub(rf"^(\|\s*`){re.escape(a.old)}(`\s*\|)", rf"\g<1>{a.new}\g<2>", text, flags=re.M)
        if new_file != file:
            text = text.replace(f"`{file}`", f"`{new_file}`")
        p.write_text(text, encoding="utf-8")
        for f in list(ctx.base.glob("*.md")) + ticket_files(ctx):
            t = f.read_text(encoding="utf-8")
            t2 = re.sub(rf"\b{re.escape(a.contract)}#{re.escape(a.old)}\b", f"{a.contract}#{a.new}", t)
            if f.parent == ctx.tix:
                fm2, _ = front_matter(t2)
                if fm2 and fm2.get("contract") == a.contract and fm2.get("clause") == a.old:
                    t2 = set_field(t2, "clause", a.new)
                    t2 = append_log(t2, a.actor, "note", f"clause renamed {a.old} -> {a.new}")
            if t2 != t:
                f.write_text(t2, encoding="utf-8")
    elif a.ccmd == "remove":
        if a.name not in clauses:
            sys.exit(f"{a.contract} has no clause {a.name}")
        typ, file = rows.get(a.name, (None, ""))
        text = drop_table_row(drop_table_row(text, "Clauses", a.name), "Verification", a.name)
        p.write_text(text, encoding="utf-8")
        if typ and typ != "covered-by" and (ctx.tests / file).exists():
            (ctx.tests / file).unlink()
        t = find_ticket_for(ctx, a.contract, a.name)
        if t:
            fm2, _ = front_matter(t.read_text(encoding="utf-8"))
            if fm2["status"] in ("open", "rerouted"):
                change_status(ctx, t.stem, "obsolete", a.actor, f"clause {a.name} removed")
        print("removed; parents that cite it in `covered-by` will fail the lint until they are fixed")
    return finish(ctx)


def cmd_edge(ctx, a):
    pp, ptext, pfm = read_fm(ctx, a.parent)
    cp, ctext, cfm = read_fm(ctx, a.child)
    enf, imp = list(pfm.get("enforces") or []), list(cfm.get("implements") or [])
    if a.ecmd == "add":
        if a.child not in enf:
            enf.append(a.child)
        if a.parent not in imp:
            imp.append(a.parent)
    else:
        enf = [e for e in enf if e != a.child]
        imp = [i for i in imp if i != a.parent]
    pp.write_text(set_list(ptext, "enforces", enf), encoding="utf-8")
    cp.write_text(set_list(ctext, "implements", imp), encoding="utf-8")
    return finish(ctx)


def cmd_files(ctx, a):
    p, text, fm = read_fm(ctx, a.contract)
    enf = list(fm.get("enforces") or [])
    for f in a.paths:
        if not is_path(f):
            sys.exit(f"{f} is not a path: use `edge` for contracts")
        if a.fcmd == "add" and f not in enf:
            enf.append(f)
        if a.fcmd == "remove":
            enf = [e for e in enf if e != f]
    p.write_text(set_list(text, "enforces", enf), encoding="utf-8")
    return finish(ctx)


def cmd_root(ctx, a):
    p, text, _ = read_fm(ctx, a.contract)
    p.write_text(set_flag(text, a.rcmd == "set"), encoding="utf-8")
    return finish(ctx)


def retarget(ctx, t, old, new):
    """Rewrite the references to a renamed contract: id#clause, test paths, links to its file."""
    trel = rel(ctx.tests, ctx.root)
    t = re.sub(rf"(?<![\w/-]){re.escape(old)}#", f"{new}#", t)
    t = t.replace(f"`{old}/", f"`{new}/").replace(f"{trel}/{old}/", f"{trel}/{new}/")
    return t.replace(f"]({old}.md", f"]({new}.md").replace(f"contracts/{old}.md", f"contracts/{new}.md")


def cmd_contract(ctx, a):
    if a.kcmd == "new":
        if not NAME.match(a.id):
            sys.exit("contract ID must be 1-3 words of a-z, 0-9, joined by _")
        if ctx.cpath(a.id).exists():
            sys.exit(f"{a.id} exists")
        imp = [x for x in (a.implements or "").split(",") if x]
        enf = [x for x in (a.enforces or "").split(",") if x]
        ctx.base.mkdir(parents=True, exist_ok=True)
        head = ["---", f"name: {a.name}"] + (["root: yes"] if a.is_root else []) + \
               [f"implements: [{', '.join(imp)}]", "enforces:"] + [f"  - {e}" for e in enf] + ["---"]
        ctx.cpath(a.id).write_text(
            "\n".join(head) + f"\n\n# {a.name}\n\n## Purpose\n{TODO}\n\n## View\n{TODO}\n\n## Clauses\n\n| Name | Clause |\n|---|---|\n\n"
            f"## Verification\n\n| Name | Type | Proves | File |\n|---|---|---|---|\n", encoding="utf-8")
        for p in imp:
            if ctx.cpath(p).exists():
                pp, pt, pfm = read_fm(ctx, p)
                en = list(pfm.get("enforces") or [])
                if a.id not in en:
                    pp.write_text(set_list(pt, "enforces", en + [a.id]), encoding="utf-8")
        for c in [e for e in enf if not is_path(e)]:
            if ctx.cpath(c).exists():
                cp, ct, cfm = read_fm(ctx, c)
                im = list(cfm.get("implements") or [])
                if a.id not in im:
                    cp.write_text(set_list(ct, "implements", im + [a.id]), encoding="utf-8")
    else:
        old, new = a.old, a.new
        if not NAME.match(new) or ctx.cpath(new).exists():
            sys.exit("the new ID must be 1-3 words of a-z, 0-9, joined by _, and unused")
        read_fm(ctx, old)
        ctx.cpath(old).rename(ctx.cpath(new))
        if (ctx.tests / old).is_dir():
            (ctx.tests / old).rename(ctx.tests / new)
        for cid in ctx.contract_ids():
            p = ctx.cpath(cid)
            t = p.read_text(encoding="utf-8")
            fm, _ = front_matter(t)
            for key in ("implements", "enforces"):
                items = fm.get(key) or []
                if old in items:
                    t = set_list(t, key, [new if i == old else i for i in items])
            t = retarget(ctx, t, old, new)
            if t != p.read_text(encoding="utf-8"):
                p.write_text(t, encoding="utf-8")
        for f in ticket_files(ctx):
            t = f.read_text(encoding="utf-8")
            fm, _ = front_matter(t)
            t2 = retarget(ctx, t, old, new)
            if fm and fm.get("contract") == old:
                t2 = set_field(t2, "contract", new)
                t2 = append_log(t2, a.actor, "note", f"contract renamed {old} -> {new}")
            if t2 != t:
                f.write_text(t2, encoding="utf-8")
        if (ctx.ws / "scope.txt").exists():
            s = (ctx.ws / "scope.txt").read_text(encoding="utf-8").split("\n")
            (ctx.ws / "scope.txt").write_text("\n".join(new if x == old else x for x in s), encoding="utf-8")
    return finish(ctx)


# --------------------------------------------------------------------------- scope, summary, handoff

def scope_items(ctx):
    f = ctx.ws / "scope.txt"
    return [l for l in f.read_text(encoding="utf-8").splitlines() if l.strip()] if f.exists() else []


def cmd_scope(ctx, a):
    f = ctx.ws / "scope.txt"
    items = scope_items(ctx)
    if a.scmd == "add":
        for x in a.items:
            if x not in items:
                items.append(x)
        f.write_text("\n".join(items) + "\n", encoding="utf-8")
    elif a.scmd == "clear":
        f.write_text("", encoding="utf-8")
    else:
        print("\n".join(items))
    return 0


def tickets_by(ctx):
    out = []
    for f in ticket_files(ctx):
        fm, _ = front_matter(f.read_text(encoding="utf-8"))
        if fm:
            out.append(fm)
    return out


def cmd_summary(ctx, a):
    errors, zones, fms, _ = run_lint(ctx, quiet=True)
    tix = tickets_by(ctx)
    by = {s: [t for t in tix if t.get("status") == s] for s in STATUSES}
    dirs = {d: len([t for t in by["open"] if t.get("direction") == d]) for d in sorted(DIRECTIONS)}
    print(f"Tickets: open {len(by['open'])} ({', '.join(f'{d} {n}' for d, n in dirs.items())}), rerouted {len(by['rerouted'])}, "
          f"resolved {len(by['resolved'])}, obsolete {len(by['obsolete'])}")
    for t in by["open"] + by["rerouted"]:
        print(f"  {t['id']}  {t['status']}  {t['direction']}  {t['contract']}#{t['clause']}")
    sc = scope_items(ctx)
    print(f"Scope: {len(sc)} entries" + (": " + ", ".join(sc) if sc else ""))
    orphans = [c for c, fm in fms.items() if fm.get("root") != "yes" and not fm.get("implements")]
    print(f"Lint: {len(errors)} problems, {len(zones)} uncontracted files, {len(orphans)} orphans")
    open_work = by["open"] or by["rerouted"]
    if errors or zones or open_work:
        print("State: NOT STABLE")
    else:
        print("State: nothing open. Stable only if `verify` passes every clause and the judged ones hold.")
    return 0


def cmd_handoff(ctx, a):
    d = ctx.ws / "handoff"
    d.mkdir(parents=True, exist_ok=True)
    tix = tickets_by(ctx)

    def tl(pred):
        return [f"- [{t['id']}](../tickets/{t['id']}.md) · {t['contract']}#{t['clause']}" for t in tix if pred(t)] or ["- none"]

    out = [f"# Handoff {now()}", "", "## Stopped at", a.stopped_at + (f" ({a.why})" if a.why else ""), "", "## Scope"]
    out += [f"- {x}" for x in scope_items(ctx)] or ["- empty"]
    out += ["", "## Tickets"]
    for dname in ("code", "contract", "escalate"):
        out += [f"**{dname}**"] + tl(lambda t, dname=dname: t["status"] == "open" and t["direction"] == dname)
    out += ["**rerouted**"] + tl(lambda t: t["status"] == "rerouted")
    out += ["", "## Decisions", a.decisions or "none", "", "## Next", a.next or "run `summary` and ask", "",
            "## Suggested skills", a.skills or "contract-flow"]
    f = d / f"{datetime.now().strftime('%Y-%m-%d-%H%M')}.md"
    f.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f)
    return 0


