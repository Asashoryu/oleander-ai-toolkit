def ticket_files(ctx):
    return sorted(ctx.tix.glob("*.md")) if ctx.tix.is_dir() else []


def parse_log(body):
    sec = dict(sections(body)).get("Log", "")
    entries, bad = [], []
    for line in sec.splitlines():
        if not line.strip() or line.startswith("<!--"):
            continue
        m = LOG_LINE.match(line)
        if m:
            entries.append(m.groups())
        else:
            bad.append(line)
    return entries, bad


def derive(entries, err):
    """Replay the log. Return (status, direction) and report impossible steps."""
    status = direction = None
    last = ""
    for i, (ts, actor, ev, detail) in enumerate(entries):
        if ts < last:
            err(f"log entry {i + 1} is older than the one before it")
        last = ts
        if ev not in EVENTS:
            err(f"log entry {i + 1}: unknown event `{ev}`")
            continue
        if i == 0 and ev != "opened":
            err("the first log entry must be `opened`")
        if i > 0 and ev == "opened":
            err(f"log entry {i + 1}: `opened` only comes first")
        if not detail.strip():
            err(f"log entry {i + 1}: `{ev}` needs a detail")
        if ev == "opened":
            m = re.match(r"^(\w+): (.+)$", detail)
            if not m or m.group(1) not in DIRECTIONS:
                err("`opened` detail must be `<direction>: <reason>`")
            else:
                status, direction = "open", m.group(1)
        elif ev in ("status_changed", "direction_changed"):
            m = re.match(r"^(\w+) -> (\w+): (.+)$", detail)
            if not m:
                err(f"log entry {i + 1}: detail must be `<from> -> <to>: <reason>`")
                continue
            a, b = m.group(1), m.group(2)
            cur = status if ev == "status_changed" else direction
            if a != cur:
                err(f"log entry {i + 1}: says it was `{a}`, the log says `{cur}`")
            if ev == "status_changed":
                if b not in TRANSITIONS.get(a, set()):
                    err(f"log entry {i + 1}: `{a}` -> `{b}` is not allowed")
                status = b
            else:
                if b not in DIRECTIONS:
                    err(f"log entry {i + 1}: `{b}` is not a direction")
                direction = b
        elif ev == "reopened":
            if status not in REOPENABLE:
                err(f"log entry {i + 1}: only a closed or rerouted ticket can be reopened")
            status = "open"
    return status, direction


def lint_tickets(ctx, fms, ids, errors):
    names, pairs = set(), {}
    for f in ticket_files(ctx):
        stem = f.stem

        def err(msg, stem=stem):
            errors.append(f"ticket {stem}: {msg}")

        m = re.match(r"^T-(.+)$", stem)
        if not m or not NAME.match(m.group(1)):
            err("file name must be T-<1-3 words of a-z, 0-9 joined by _>")
            continue
        if stem in names:
            err("duplicate")
        names.add(stem)
        text = f.read_text(encoding="utf-8")
        fm, body = front_matter(text)
        if fm is None:
            err("no front matter")
            continue
        if fm.get("id") != stem:
            err("`id` differs from file name")
        for k in ("status", "direction", "contract", "clause"):
            if not fm.get(k):
                err(f"`{k}` missing")
        if fm.get("status") not in STATUSES:
            err(f"`status` must be one of {sorted(STATUSES)}")
        if fm.get("direction") not in DIRECTIONS:
            err(f"`direction` must be one of {sorted(DIRECTIONS)}")
        c, k = fm.get("contract"), fm.get("clause")
        if (c, k) in pairs:
            err(f"a second ticket for {c}#{k} (already {pairs[(c, k)]}): reopen that one")
        pairs[(c, k)] = stem
        if fm.get("status") in ("open", "rerouted") and (c not in ids or k not in (fms.get(c, {}).get("_clauses") or [])):
            err(f"{c}#{k} no longer exists: run `ticket sweep`")
        titles = [t for t, _ in sections(body)]
        if titles != TICKET_SECTIONS:
            err(f"sections must be {', '.join(TICKET_SECTIONS)} in this order; found: {', '.join(titles) or 'none'}")
            continue
        for t, content in sections(body):
            if t != "Log" and TODO in content:
                err(f"section {t} is not written yet")
        entries, bad = parse_log(body)
        for b in bad:
            err(f"log line does not follow `- <time> · <actor> · <event> · <detail>`: {b[:60]}")
        if not entries:
            err("the log is empty")
            continue
        status, direction = derive(entries, err)
        if status and status != fm.get("status"):
            err(f"`status` is {fm.get('status')} but the log ends at {status}")
        if direction and direction != fm.get("direction"):
            err(f"`direction` is {fm.get('direction')} but the log ends at {direction}")
        check_refs(ctx, text, f, f"ticket {stem}", ids, fms, errors)


def load_all(ctx):
    errors = []
    ids = set(ctx.contract_ids())
    fms = {}
    if ctx.base.is_dir():
        for sub in ctx.base.rglob("*.md"):
            if sub.parent != ctx.base:
                errors.append(f"{sub.relative_to(ctx.base).with_suffix('').as_posix()}: contracts live directly in contracts/, without subfolders")
    for cid in sorted(ids):
        fm = lint_contract(ctx, ctx.cpath(cid), cid, ids, errors)
        if fm is not None:
            fms[cid] = fm
    return ids, fms, errors


def run_lint(ctx, quiet=False):
    ids, fms, errors = load_all(ctx)
    level = lint_graph(fms, errors)
    stale_verifications(ctx, fms, errors)
    for cid, fm in fms.items():
        check_refs(ctx, fm["_text"], ctx.cpath(cid), cid, ids, fms, errors)
    if ids:
        write_links(ctx, fms, level)
    lint_tickets(ctx, fms, ids, errors)
    zones = coverage(ctx, fms)
    if not quiet:
        for e in errors:
            print("FAIL", e)
        for z in zones or []:
            print("ZONE", z, "is not enforced by any leaf contract")
        if zones is None:
            print("NOTE  Contracted domain is not set in the README Configuration: coverage not checked")
        print(f"{len(ids)} contracts checked, {len(errors)} problems, {len(zones or [])} uncontracted files")
    return errors, zones or [], fms, level


