def ext_for(ctx, given=None):
    if given:
        return Path(given).suffix or None
    r = ctx.runner()
    if not r:
        return None
    return {"python": ".py", "python3": ".py", "py": ".py", "bash": ".sh", "sh": ".sh", "pwsh": ".ps1",
            "powershell": ".ps1", "node": ".js"}.get(Path(r[0]).name)


def stub_text(ext, label):
    msg = f"{STUB}: {label}"
    return {".py": f'import sys\nprint("{msg}")\nsys.exit(1)\n',
            ".sh": f'#!/usr/bin/env bash\necho "{msg}" >&2\nexit 1\n',
            ".ps1": f'Write-Error "{msg}"\nexit 1\n',
            ".js": f'console.error("{msg}");\nprocess.exit(1);\n',
            ".md": f"# {label}\n\n## Look at\n- {TODO}\n\n## Criteria\n1. {TODO}\n\n## Fails when\n{STUB.upper()}: {TODO}\n"
            }.get(ext, f"{msg}\n")


def run_check(ctx, file):
    r = ctx.runner()
    if not r:
        return None, "Script runner is not set in the README Configuration"
    try:
        p = subprocess.run(r + [str(ctx.tests / file)], cwd=ctx.root, capture_output=True, text=True, timeout=300)
    except (OSError, subprocess.TimeoutExpired) as e:
        return False, str(e)
    return p.returncode == 0, (p.stdout + p.stderr).strip()


def verify_clause(ctx, fm, cid, clause):
    """Return ('PASS'|'FAIL'|'JUDGE', note)."""
    typ, file = (fm.get("_rows") or {}).get(clause, (None, None))
    if typ is None:
        return "FAIL", "no verification row"
    if typ == "covered-by":
        return "JUDGE", f"covered by {file}"
    if typ == "ai-check":
        p = ctx.tests / file
        if not p.exists():
            return "FAIL", "check file missing"
        if STUB.upper() in p.read_text(encoding="utf-8"):
            return "FAIL", STUB
        return "JUDGE", file
    if not (ctx.tests / file).exists():
        return "FAIL", "verification file missing"
    ok, out = run_check(ctx, file)
    if ok is None:
        return "FAIL", out
    return ("PASS", "") if ok else ("FAIL", out.splitlines()[-1][:160] if out else "exit code not 0")


def cmd_verify(ctx, a):
    ids, fms, _ = load_all(ctx)
    wanted = a.contract or sorted(fms)
    counts = {"PASS": 0, "FAIL": 0, "JUDGE": 0}
    for cid in wanted:
        fm = fms.get(cid)
        if fm is None:
            print("FAIL", cid, "unknown or unreadable contract")
            counts["FAIL"] += 1
            continue
        for clause in fm.get("_clauses", []):
            res, note = verify_clause(ctx, fm, cid, clause)
            counts[res] += 1
            print(f"{res:5} {cid}#{clause} {note}".rstrip())
    print(f"{counts['PASS']} passed, {counts['FAIL']} failed, {counts['JUDGE']} to judge")
    return 1 if counts["FAIL"] else 0


